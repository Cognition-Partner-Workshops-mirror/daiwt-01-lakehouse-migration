"""Regenerate as-of SQL and bronze job metadata from bronze DDL / manifest."""
import json
import re
from pathlib import Path

import yaml

from bronze_schema import bronze_tables

ROOT = Path(__file__).resolve().parents[1]


def manifest_drops(manifest):
    result = {}
    for drop in manifest['drops']:
        name = drop['name']
        if name in result:
            raise ValueError(f'Duplicate drop: {name}')
        counts = {entry['table']: entry['row_count'] for entry in manifest['files']
                  if entry.get('format') == 'csv' and entry['path'].startswith(f'inputs/{name}/')}
        if not counts or drop.get('batch_id') is None or not drop.get('business_date'):
            raise ValueError(f'Incomplete drop metadata: {name}')
        result[name] = dict(batch_id=drop['batch_id'], business_date=drop['business_date'], counts=counts)
    return result


def qualified(schema):
    return "('`' || replace(:catalog, '`', '``') || '`.`' || replace(:" + schema + ", '`', '``') || '`')"


def dynamic(sql):
    pieces = []
    for index, piece in enumerate(re.split(r'(\{silver\}|\{bronze\})', sql)):
        if index % 2:
            pieces.append(qualified(piece[1:-1] + '_schema'))
        else:
            pieces.append("'" + piece.replace('\\', '\\\\').replace("'", "\\'") + "'")
    return 'EXECUTE IMMEDIATE\n  ' + ' || '.join(pieces) + ';\n'


def functions(tables):
    union = '\n       UNION ALL\n       '.join(
        f'SELECT _drop, _loaded_at FROM {{bronze}}.`{table}`' for table in tables)
    sql = r"""-- Generated by ci/generate_silver_asof.py; source columns come from bronze load.sql.
CREATE OR REPLACE FUNCTION IDENTIFIER(:catalog || '.' || :silver_schema || '.drop_seq')(d STRING)
RETURNS INT
DETERMINISTIC
RETURN CASE WHEN d RLIKE r'^D[0-9]+\z' THEN try_cast(substring(d, 2) AS INT) ELSE NULL END;

"""
    sql += dynamic('''CREATE OR REPLACE FUNCTION {silver}.`resolve_drop`(as_of_drop STRING)
RETURNS STRING
RETURN (
  WITH loaded AS (
       ''' + union + '''
  ), candidates AS (
    SELECT _drop, {silver}.`drop_seq`(_drop) AS seq, max(_loaded_at) AS loaded_at
    FROM loaded GROUP BY _drop
  )
  SELECT _drop FROM candidates
  WHERE seq <= {silver}.`drop_seq`(as_of_drop)
  ORDER BY seq DESC, loaded_at DESC, _drop DESC
  LIMIT 1
)''')
    for table, columns in tables.items():
        declaration = ', '.join(c['name'] + ' ' + c['type'] for c in columns)
        projection = ', '.join(c['name'] for c in columns)
        sql += '\n' + dynamic(f'''CREATE OR REPLACE FUNCTION {{silver}}.`asof_{table}`(as_of_drop STRING)
RETURNS TABLE ({declaration})
RETURN SELECT {projection}
FROM {{bronze}}.`{table}`
WHERE _drop = {{silver}}.`resolve_drop`(as_of_drop)''')
    return sql


def self_check(tables):
    seq = "IDENTIFIER(:catalog || '.' || :silver_schema || '.drop_seq')"
    resolve = "IDENTIFIER(:catalog || '.' || :silver_schema || '.resolve_drop')"
    sql = f"""-- Generated by ci/generate_silver_asof.py.
WITH cases(d, expected) AS (
  VALUES ('D0', 0), ('D2', 2), ('D10', 10), ('D01', 1),
         ('D-1', CAST(NULL AS INT)), ('D2x', CAST(NULL AS INT)),
         ('D2147483648', CAST(NULL AS INT)), ('', CAST(NULL AS INT)),
         ('d1', CAST(NULL AS INT)), (CAST(NULL AS STRING), CAST(NULL AS INT))
)
SELECT CASE WHEN count(*) = 10 AND count_if(NOT ({seq}(d) <=> expected)) = 0
            THEN 'PASS drop_seq' ELSE raise_error('drop_seq semantics drift') END
FROM cases;

SELECT CASE WHEN {resolve}(:drop) IS NOT NULL AND {resolve}('invalid') IS NULL
                 AND {resolve}(CAST(NULL AS STRING)) IS NULL
            THEN 'PASS resolve_drop' ELSE raise_error('No eligible landed drop or invalid resolver behavior') END;
"""
    for table, columns in tables.items():
        projection = ', '.join(c['name'] for c in columns)
        function = f"IDENTIFIER(:catalog || '.' || :silver_schema || '.asof_{table}')(:drop)"
        source = f"IDENTIFIER(:catalog || '.' || :bronze_schema || '.{table}') WHERE _drop = {resolve}(:drop)"
        sql += f"""
SELECT CASE WHEN (SELECT count(*) FROM {function}) = (SELECT count(*) FROM {source})
                 AND NOT EXISTS (
                   (SELECT {projection} FROM {function})
                   EXCEPT ALL
                   (SELECT {projection} FROM {source})
                 )
            THEN 'PASS asof_{table}' ELSE raise_error('asof_{table}: snapshot mismatch') END;
"""
    return sql


def generated(root=ROOT):
    root = Path(root)
    tables = bronze_tables(root)
    job_path = 'src/sql/units/bronze_landing/bronze_landing.job.yml'
    document = yaml.safe_load((root / job_path).read_text())
    job = document['resources']['jobs']['bronze_landing']
    metadata = manifest_drops(json.loads((root / 'golden/manifest.json').read_text()))
    job['parameters'] = [dict(name='drop', default='D0'), dict(name='manifest_drops', default=json.dumps(metadata, separators=(',', ':')))]
    for task in job['tasks']:
        task['sql_task']['parameters']['manifest_drops'] = '{{job.parameters.manifest_drops}}'
    return {
        'src/sql/units/silver_asof/functions.sql': functions(tables),
        'src/sql/units/silver_asof/self_check.sql': self_check(tables),
        job_path: yaml.safe_dump(document, sort_keys=False, width=120),
    }


if __name__ == '__main__':
    for name, content in generated().items():
        (ROOT / name).write_text(content)
